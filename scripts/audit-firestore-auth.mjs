#!/usr/bin/env node

import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const DEFAULT_PROJECT_ID = 'gen-lang-client-0888019226';
const DEFAULT_DATABASE = '(default)';
const REPORT_DIR = 'migration-backups';
const DEFAULT_TECHNICAL_EMAIL_SUFFIXES = ['@auth.spcontabil.local', '.local'];

const usage = `
Usage:
  node scripts/audit-firestore-auth.mjs [options]

Options:
  --project <id>       Firebase project id. Default: ${DEFAULT_PROJECT_ID}
  --out <path>         JSON report path. Default: migration-backups/firestore-auth-audit-<timestamp>.json
  --auth-export <path> Existing Firebase Auth export JSON to cross-check accounts.
  --export-auth        Export Firebase Auth with firebase-tools, parse it, then delete the temp file.
  --keep-auth-export   Keep the temp auth export generated by --export-auth. It contains password hashes.
  --technical-email-suffix <suffix>
                       Extra technical/local email suffix to flag. Repeatable.
  --cleanup-legacy-password-fields
                       Remove passwordHash/passwordUpdatedAt from users after writing a local backup.
  --fail-on-findings   Exit with code 1 when high or critical findings exist.
  --help               Show this help.
`;

const parseArgs = (argv) => {
  const args = {
    projectId: process.env.FIREBASE_PROJECT_ID || DEFAULT_PROJECT_ID,
    out: '',
    authExport: '',
    exportAuth: false,
    keepAuthExport: false,
    technicalEmailSuffixes: [...DEFAULT_TECHNICAL_EMAIL_SUFFIXES],
    cleanupLegacyPasswordFields: false,
    failOnFindings: false,
  };

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === '--project') args.projectId = argv[++index];
    else if (arg === '--out') args.out = argv[++index];
    else if (arg === '--auth-export') args.authExport = argv[++index];
    else if (arg === '--export-auth') args.exportAuth = true;
    else if (arg === '--keep-auth-export') args.keepAuthExport = true;
    else if (arg === '--technical-email-suffix') args.technicalEmailSuffixes.push(argv[++index]);
    else if (arg === '--cleanup-legacy-password-fields') args.cleanupLegacyPasswordFields = true;
    else if (arg === '--fail-on-findings') args.failOnFindings = true;
    else if (arg === '--help' || arg === '-h') {
      console.log(usage.trim());
      process.exit(0);
    } else {
      throw new Error(`Unknown option: ${arg}`);
    }
  }

  return args;
};

const timestampForFile = () => new Date().toISOString().replace(/[-:]/g, '').replace(/\.\d{3}Z$/, 'Z');
const normalize = (value) => String(value || '').trim().toLowerCase();
const clean = (value) => String(value || '').trim();
const hasOwn = (object, key) => Object.prototype.hasOwnProperty.call(object || {}, key);
const normalizeEmailSuffix = (suffix) => {
  const normalized = normalize(suffix);
  if (!normalized) return '';
  if (normalized.startsWith('@') || normalized.startsWith('.')) return normalized;
  return `@${normalized}`;
};
const normalizeEmailSuffixes = (suffixes) => [...new Set(suffixes.map(normalizeEmailSuffix).filter(Boolean))];
const isTechnicalEmail = (email, suffixes) => {
  const normalized = normalize(email);
  return Boolean(normalized) && suffixes.some((suffix) => normalized.endsWith(suffix));
};

const parseFirestoreValue = (value) => {
  if (!value || typeof value !== 'object') return undefined;
  if (hasOwn(value, 'stringValue')) return value.stringValue;
  if (hasOwn(value, 'booleanValue')) return value.booleanValue;
  if (hasOwn(value, 'integerValue')) return Number(value.integerValue);
  if (hasOwn(value, 'doubleValue')) return Number(value.doubleValue);
  if (hasOwn(value, 'timestampValue')) return value.timestampValue;
  if (hasOwn(value, 'nullValue')) return null;
  if (hasOwn(value, 'arrayValue')) return (value.arrayValue.values || []).map(parseFirestoreValue);
  if (hasOwn(value, 'mapValue')) {
    return Object.fromEntries(
      Object.entries(value.mapValue.fields || {}).map(([key, nestedValue]) => [key, parseFirestoreValue(nestedValue)]),
    );
  }
  return undefined;
};

const parseFirestoreDocument = (document) => ({
  id: decodeURIComponent(document.name.split('/').pop() || ''),
  path: document.name,
  createTime: document.createTime,
  updateTime: document.updateTime,
  data: Object.fromEntries(
    Object.entries(document.fields || {}).map(([key, value]) => [key, parseFirestoreValue(value)]),
  ),
});

const getAccessToken = () => {
  if (process.env.GOOGLE_OAUTH_ACCESS_TOKEN) return process.env.GOOGLE_OAUTH_ACCESS_TOKEN.trim();
  return execFileSync('gcloud', ['auth', 'print-access-token'], { encoding: 'utf8' }).trim();
};

const requestJson = async (url, token) => {
  const response = await fetch(url, {
    headers: {
      Authorization: `Bearer ${token}`,
      Accept: 'application/json',
    },
  });

  if (!response.ok) {
    const body = await response.text();
    throw new Error(`Firestore request failed (${response.status}) for ${url}: ${body.slice(0, 500)}`);
  }

  return response.json();
};

const listCollection = async (projectId, collection, token) => {
  const docs = [];
  let pageToken = '';
  do {
    const params = new URLSearchParams({ pageSize: '300' });
    if (pageToken) params.set('pageToken', pageToken);
    const url = `https://firestore.googleapis.com/v1/projects/${projectId}/databases/${encodeURIComponent(DEFAULT_DATABASE)}/documents/${collection}?${params.toString()}`;
    const payload = await requestJson(url, token);
    docs.push(...(payload.documents || []).map(parseFirestoreDocument));
    pageToken = payload.nextPageToken || '';
  } while (pageToken);

  return docs;
};

const firestoreDocumentUrl = (projectId, documentPath) =>
  `https://firestore.googleapis.com/v1/projects/${projectId}/databases/${encodeURIComponent(DEFAULT_DATABASE)}/documents/${documentPath}`;

const firestoreValue = (value) => {
  if (value === null) return { nullValue: null };
  if (typeof value === 'boolean') return { booleanValue: value };
  if (typeof value === 'number') {
    return Number.isInteger(value) ? { integerValue: String(value) } : { doubleValue: value };
  }
  if (Array.isArray(value)) return { arrayValue: { values: value.map(firestoreValue) } };
  if (typeof value === 'object') {
    return {
      mapValue: {
        fields: Object.fromEntries(Object.entries(value).map(([key, nestedValue]) => [key, firestoreValue(nestedValue)])),
      },
    };
  }
  return { stringValue: String(value) };
};

const patchDocumentFields = async (projectId, documentPath, token, fields, fieldPaths) => {
  const params = new URLSearchParams();
  for (const fieldPath of fieldPaths) params.append('updateMask.fieldPaths', fieldPath);
  const response = await fetch(`${firestoreDocumentUrl(projectId, documentPath)}?${params.toString()}`, {
    method: 'PATCH',
    headers: {
      Authorization: `Bearer ${token}`,
      Accept: 'application/json',
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      fields: Object.fromEntries(Object.entries(fields).map(([key, value]) => [key, firestoreValue(value)])),
    }),
  });

  if (!response.ok) {
    const body = await response.text();
    throw new Error(`Firestore patch failed (${response.status}) for ${documentPath}: ${body.slice(0, 500)}`);
  }

  return response.json();
};

const exportFirebaseAuth = (projectId, stamp) => {
  mkdirSync(REPORT_DIR, { recursive: true });
  const outputPath = resolve(REPORT_DIR, `auth-export-${stamp}.json`);
  execFileSync('firebase', ['auth:export', outputPath, '--format=json', '--project', projectId], {
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  });
  return outputPath;
};

const loadAuthUsers = (path) => {
  if (!path) return null;
  const payload = JSON.parse(readFileSync(path, 'utf8'));
  const users = Array.isArray(payload) ? payload : payload.users || [];
  const byUid = new Map();
  const byEmail = new Map();

  for (const account of users) {
    const uid = clean(account.localId || account.uid);
    const email = normalize(account.email);
    if (uid) byUid.set(uid, account);
    if (email) byEmail.set(email, account);
  }

  return {
    users,
    byUid,
    byEmail,
  };
};

const severityRank = {
  critical: 0,
  high: 1,
  medium: 2,
  low: 3,
};

const addFinding = (findings, severity, code, subject, message, details = {}) => {
  findings.push({ severity, code, subject, message, ...details });
};

const summarizeUser = (doc, loginIndex, authStatus, recoveryEmailStatus) => {
  const data = doc.data;
  return {
    id: doc.id,
    username: data.username || '',
    name: data.name || '',
    email: data.email || '',
    role: data.role || '',
    active: data.active === true,
    status: data.status || '',
    authUid: data.authUid || '',
    authEmail: data.authEmail || '',
    hasPasswordHash: hasOwn(data, 'passwordHash'),
    loginIndex,
    authStatus,
    recoveryEmailStatus,
  };
};

const formatFinding = (finding) => {
  const subject = finding.subject ? ` (${finding.subject})` : '';
  return `- [${finding.severity.toUpperCase()}] ${finding.code}${subject}: ${finding.message}`;
};

const buildMarkdown = (report) => {
  const criticalOrHigh = report.findings.filter((finding) => ['critical', 'high'].includes(finding.severity));
  const cleanupCandidates = report.cleanupCandidates.legacyPasswordFieldUserIds;
  const recoveryEmailRisks = report.recoveryEmail.risks;

  return [
    `# Firestore Auth Audit`,
    ``,
    `Generated at: ${report.generatedAt}`,
    `Project: ${report.projectId}`,
    `Auth export checked: ${report.authExport.checked ? 'yes' : 'no'}`,
    ``,
    `## Counts`,
    ``,
    `- Users: ${report.counts.users}`,
    `- Login index docs: ${report.counts.loginIndex}`,
    `- Firebase Auth accounts checked: ${report.counts.authUsersChecked}`,
    `- Findings: ${report.counts.findings}`,
    `- Critical: ${report.counts.bySeverity.critical}`,
    `- High: ${report.counts.bySeverity.high}`,
    `- Medium: ${report.counts.bySeverity.medium}`,
    `- Low: ${report.counts.bySeverity.low}`,
    ``,
    `## Priority Findings`,
    ``,
    ...(criticalOrHigh.length ? criticalOrHigh.map(formatFinding) : ['- None.']),
    ``,
    `## Legacy Cleanup Candidates`,
    ``,
    cleanupCandidates.length
      ? cleanupCandidates.map((userId) => `- users/${userId}: remove passwordHash/passwordUpdatedAt`).join('\n')
      : '- None.',
    ``,
    `## Recovery Email Risks`,
    ``,
    recoveryEmailRisks.length
      ? recoveryEmailRisks
          .map((risk) => `- users/${risk.userId} (${risk.username}): authEmail ${risk.authEmail} is not deliverable for password reset.`)
          .join('\n')
      : '- None.',
    ``,
    `## Next Actions`,
    ``,
    ...report.nextActions.map((action) => `- ${action}`),
    ``,
  ].join('\n');
};

const main = async () => {
  const args = parseArgs(process.argv.slice(2));
  args.technicalEmailSuffixes = normalizeEmailSuffixes(args.technicalEmailSuffixes);
  const stamp = timestampForFile();
  const outPath = resolve(args.out || `${REPORT_DIR}/firestore-auth-audit-${stamp}.json`);
  const markdownPath = outPath.replace(/\.json$/i, '.md');

  mkdirSync(dirname(outPath), { recursive: true });

  let generatedAuthExport = '';
  let authExportPath = args.authExport ? resolve(args.authExport) : '';
  if (args.exportAuth) {
    generatedAuthExport = exportFirebaseAuth(args.projectId, stamp);
    authExportPath = generatedAuthExport;
  }

  const token = getAccessToken();
  const [userDocs, loginIndexDocs] = await Promise.all([
    listCollection(args.projectId, 'users', token),
    listCollection(args.projectId, 'loginIndex', token),
  ]);

  const authExport = loadAuthUsers(authExportPath);
  const usersById = new Map(userDocs.map((doc) => [doc.id, doc]));
  const loginIndexByUsername = new Map(loginIndexDocs.map((doc) => [normalize(doc.id), doc]));
  const findings = [];
  const passwordHashUserIds = [];
  const legacyPasswordFieldDocs = [];
  const recoveryEmailRisks = [];
  const summarizedUsers = [];

  for (const doc of userDocs) {
    const data = doc.data;
    const username = normalize(data.username || doc.id);
    const authUid = clean(data.authUid);
    const authEmail = normalize(data.authEmail || data.email);
    const profileEmail = normalize(data.email);
    const active = data.active === true;
    const subject = `users/${doc.id}`;
    const hasPasswordHash = hasOwn(data, 'passwordHash');
    const hasPasswordUpdatedAt = hasOwn(data, 'passwordUpdatedAt');
    const loginIndexDoc = username ? loginIndexByUsername.get(username) : null;
    let authStatus = authExport ? 'unchecked' : 'not_checked';
    let loginIndexStatus = loginIndexDoc ? 'present' : 'missing';
    let recoveryEmailStatus = authEmail ? 'deliverable_auth_email' : 'missing_auth_email';

    if (!username) {
      addFinding(findings, 'critical', 'USER_MISSING_USERNAME', subject, 'User profile has no username.');
    }

    if (hasPasswordHash) {
      passwordHashUserIds.push(doc.id);
      addFinding(findings, 'high', 'LEGACY_PASSWORD_HASH_FIELD', subject, 'User profile still contains a legacy passwordHash field.', {
        username: data.username || '',
      });
    }

    if (hasPasswordHash || hasPasswordUpdatedAt) {
      legacyPasswordFieldDocs.push(doc);
    }

    if (hasPasswordUpdatedAt) {
      addFinding(findings, 'medium', 'LEGACY_PASSWORD_UPDATED_AT_FIELD', subject, 'User profile still contains a legacy passwordUpdatedAt field.', {
        username: data.username || '',
      });
    }

    if (!authUid || !authEmail) {
      addFinding(
        findings,
        active ? 'critical' : 'medium',
        'USER_MISSING_FIREBASE_AUTH_LINK',
        subject,
        'User profile is missing authUid and/or authEmail.',
        { username: data.username || '', active },
      );
      authStatus = 'missing_link';
    }

    if (authEmail && isTechnicalEmail(authEmail, args.technicalEmailSuffixes)) {
      recoveryEmailStatus = 'technical_auth_email';
      recoveryEmailRisks.push({
        userId: doc.id,
        username: data.username || '',
        active,
        authEmail,
        profileEmail,
        reason: 'Firebase Auth password reset is sent to authEmail, but this address is technical/local.',
      });
      addFinding(
        findings,
        active ? 'high' : 'medium',
        'TECHNICAL_AUTH_EMAIL',
        subject,
        'Firebase Auth email is technical/local and cannot receive password reset emails.',
        {
          username: data.username || '',
          active,
          authEmail,
          profileEmail,
        },
      );
    }

    if (authUid && doc.id !== authUid) {
      const profileAtAuthUid = usersById.has(authUid);
      addFinding(
        findings,
        active && !profileAtAuthUid ? 'critical' : 'medium',
        profileAtAuthUid ? 'DUPLICATE_PROFILE_FOR_AUTH_UID' : 'AUTH_UID_DOC_ID_MISMATCH',
        subject,
        profileAtAuthUid
          ? `Profile doc id differs from authUid, but users/${authUid} also exists.`
          : 'Profile doc id differs from authUid and no profile exists at users/{authUid}.',
        { username: data.username || '', authUid, active },
      );
    }

    if (active && username && !loginIndexDoc) {
      addFinding(findings, 'high', 'ACTIVE_USER_MISSING_LOGIN_INDEX', subject, 'Active user has no loginIndex document for username login.', {
        username,
      });
    }

    if (loginIndexDoc) {
      const indexUid = clean(loginIndexDoc.data.uid);
      const indexEmail = normalize(loginIndexDoc.data.email);
      if (!indexUid) {
        loginIndexStatus = 'missing_uid';
        addFinding(findings, 'high', 'LOGIN_INDEX_MISSING_UID', `loginIndex/${loginIndexDoc.id}`, 'Login index document has no uid.', {
          username,
        });
      } else if (authUid && indexUid !== authUid) {
        loginIndexStatus = 'uid_mismatch';
        addFinding(findings, 'high', 'LOGIN_INDEX_UID_MISMATCH', `loginIndex/${loginIndexDoc.id}`, 'Login index uid does not match user authUid.', {
          username,
          indexUid,
          authUid,
        });
      }

      if (authEmail && indexEmail && indexEmail !== authEmail) {
        loginIndexStatus = 'email_mismatch';
        addFinding(findings, 'medium', 'LOGIN_INDEX_EMAIL_MISMATCH', `loginIndex/${loginIndexDoc.id}`, 'Login index email does not match user authEmail/email.', {
          username,
          indexEmail,
          authEmail,
        });
      }
    }

    if (authExport && authUid) {
      const account = authExport.byUid.get(authUid);
      if (!account) {
        authStatus = 'uid_missing_in_auth';
        addFinding(
          findings,
          active ? 'critical' : 'high',
          'AUTH_UID_NOT_FOUND',
          subject,
          'authUid does not exist in Firebase Auth export.',
          { username: data.username || '', authUid, active },
        );
      } else {
        authStatus = 'found';
        const accountEmail = normalize(account.email);
        if (authEmail && accountEmail && accountEmail !== authEmail) {
          authStatus = 'email_mismatch';
          addFinding(findings, 'high', 'AUTH_EMAIL_MISMATCH', subject, 'Firebase Auth account email does not match profile authEmail/email.', {
            username: data.username || '',
            authUid,
            profileEmail: authEmail,
            authEmail: accountEmail,
          });
        }

        if (account.disabled === true && active) {
          authStatus = 'disabled_auth_active_profile';
          addFinding(findings, 'high', 'ACTIVE_PROFILE_DISABLED_AUTH_ACCOUNT', subject, 'Firestore profile is active but Firebase Auth account is disabled.', {
            username: data.username || '',
            authUid,
          });
        }
      }
    }

    if (authExport && authEmail && !authExport.byEmail.has(authEmail)) {
      addFinding(
        findings,
        active ? 'critical' : 'high',
        'AUTH_EMAIL_NOT_FOUND',
        subject,
        'authEmail/email does not exist in Firebase Auth export.',
        { username: data.username || '', authEmail, active },
      );
    }

    summarizedUsers.push(summarizeUser(doc, loginIndexStatus, authStatus, recoveryEmailStatus));
  }

  for (const doc of loginIndexDocs) {
    const indexUid = clean(doc.data.uid);
    if (!indexUid) continue;
    if (!usersById.has(indexUid)) {
      addFinding(findings, 'medium', 'STALE_LOGIN_INDEX', `loginIndex/${doc.id}`, 'Login index points to a missing user profile.', {
        username: doc.id,
        uid: indexUid,
      });
    }
  }

  if (authExport) {
    for (const account of authExport.users) {
      const uid = clean(account.localId || account.uid);
      if (!uid || usersById.has(uid)) continue;
      addFinding(findings, 'medium', 'AUTH_ACCOUNT_WITHOUT_PROFILE', `auth/${uid}`, 'Firebase Auth account has no users/{uid} profile.', {
        email: account.email || '',
        disabled: account.disabled === true,
      });
    }
  }

  findings.sort((left, right) => {
    const severityDelta = severityRank[left.severity] - severityRank[right.severity];
    if (severityDelta !== 0) return severityDelta;
    return `${left.code}${left.subject}`.localeCompare(`${right.code}${right.subject}`);
  });

  const bySeverity = findings.reduce(
    (acc, finding) => {
      acc[finding.severity] += 1;
      return acc;
    },
    { critical: 0, high: 0, medium: 0, low: 0 },
  );
  const nextActions = [];
  if (findings.some((finding) => finding.code === 'USER_MISSING_FIREBASE_AUTH_LINK')) {
    nextActions.push('Migrate or recreate users with missing authUid/authEmail before granting access.');
  }
  if (findings.some((finding) => finding.code.includes('LOGIN_INDEX'))) {
    nextActions.push('Repair missing or mismatched loginIndex docs for active users that must keep username login.');
  }
  if (legacyPasswordFieldDocs.length > 0) {
    nextActions.push('After reviewing this report, remove legacy passwordHash/passwordUpdatedAt fields from Firestore user documents.');
  }
  if (recoveryEmailRisks.length > 0) {
    nextActions.push('Replace technical/local Firebase Auth emails with real deliverable emails, then update users/{uid}.authEmail, users/{uid}.email, and loginIndex/{username}.email.');
  }
  if (nextActions.length === 0) {
    nextActions.push('No auth consistency issues found. Keep this report in migration-backups and rerun after user changes.');
  } else {
    nextActions.push('Run this audit again after cleanup and keep the generated report only in migration-backups.');
  }

  const report = {
    generatedAt: new Date().toISOString(),
    projectId: args.projectId,
    authExport: {
      checked: Boolean(authExport),
      source: authExportPath ? (generatedAuthExport ? 'generated-temporary-export' : authExportPath) : '',
      keptGeneratedExport: Boolean(generatedAuthExport && args.keepAuthExport),
    },
    counts: {
      users: userDocs.length,
      loginIndex: loginIndexDocs.length,
      authUsersChecked: authExport ? authExport.users.length : 0,
      recoveryEmailRisks: recoveryEmailRisks.length,
      findings: findings.length,
      bySeverity,
    },
    cleanupCandidates: {
      passwordHashUserIds,
      legacyPasswordFieldUserIds: legacyPasswordFieldDocs.map((doc) => doc.id),
    },
    recoveryEmail: {
      technicalEmailSuffixes: args.technicalEmailSuffixes,
      risks: recoveryEmailRisks,
    },
    findings,
    users: summarizedUsers,
    nextActions,
  };

  writeFileSync(outPath, `${JSON.stringify(report, null, 2)}\n`);
  writeFileSync(markdownPath, buildMarkdown(report));

  let cleanupBackupPath = '';
  if (args.cleanupLegacyPasswordFields) {
    cleanupBackupPath = resolve(REPORT_DIR, `legacy-password-fields-backup-${stamp}.json`);
    writeFileSync(
      cleanupBackupPath,
      `${JSON.stringify(
        {
          generatedAt: new Date().toISOString(),
          projectId: args.projectId,
          fieldPathsRemoved: ['passwordHash', 'passwordUpdatedAt'],
          documents: legacyPasswordFieldDocs.map((doc) => ({
            id: doc.id,
            path: doc.path,
            createTime: doc.createTime,
            updateTime: doc.updateTime,
            data: doc.data,
          })),
        },
        null,
        2,
      )}\n`,
    );

    for (const doc of legacyPasswordFieldDocs) {
      const documentPath = `users/${encodeURIComponent(doc.id)}`;
      const fieldPaths = ['updatedAt'];
      if (hasOwn(doc.data, 'passwordHash')) fieldPaths.push('passwordHash');
      if (hasOwn(doc.data, 'passwordUpdatedAt')) fieldPaths.push('passwordUpdatedAt');
      await patchDocumentFields(args.projectId, documentPath, token, { updatedAt: new Date().toISOString() }, fieldPaths);
    }
  }

  if (generatedAuthExport && !args.keepAuthExport) {
    rmSync(generatedAuthExport, { force: true });
  }

  console.log(`Firestore/Auth audit complete for ${args.projectId}`);
  console.log(`JSON report: ${outPath}`);
  console.log(`Markdown report: ${markdownPath}`);
  console.log(`Findings: ${findings.length} (critical: ${bySeverity.critical}, high: ${bySeverity.high}, medium: ${bySeverity.medium}, low: ${bySeverity.low})`);
  console.log(`Legacy passwordHash cleanup candidates: ${passwordHashUserIds.length}`);
  console.log(`Recovery email risks: ${recoveryEmailRisks.length}`);
  if (args.cleanupLegacyPasswordFields) {
    console.log(`Legacy password fields cleaned: ${legacyPasswordFieldDocs.length}`);
    console.log(`Cleanup backup: ${cleanupBackupPath}`);
  }

  if (args.failOnFindings && (bySeverity.critical > 0 || bySeverity.high > 0)) {
    process.exitCode = 1;
  }
};

main().catch((error) => {
  console.error(error.message || error);
  process.exit(1);
});
