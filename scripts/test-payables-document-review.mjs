import assert from 'node:assert/strict';
import { reviewPayableDocuments } from './lib/payables-document-review.mjs';
const payable = { submissionId: 'demo', identificacaoUnica: 'TEST-1', dueDate: '2026-10-10', amount: 123.45, docPago: 'SIM', description: 'Test expense' };
const good = { id: 'trx-jf-demo', data: { dueDate: payable.dueDate, valuePaid: payable.amount, status: 'Pago', description: payable.description, movement: 'Saída', type: 'Contas a Pagar' } };
assert.deepEqual(reviewPayableDocuments(payable, [good]), { mismatches: [], duplicate: null });
const bad = { id: 'legacy', data: { ...good.data, valuePaid: 555 } };
const result = reviewPayableDocuments(payable, [good, bad]);
assert.equal(result.duplicate.firestoreIds.length, 2);
assert.equal(result.mismatches.length, 1);
assert.equal(result.mismatches[0].firestoreId, 'legacy');
assert.ok(result.mismatches[0].identityReviewReasons.includes('MULTIPLE_ACTIVE_DOCUMENTS'));
assert.ok(result.mismatches[0].identityReviewReasons.includes('LEGACY_LINK_WITHOUT_UNIQUE_IDENTITY'));
assert.equal(reviewPayableDocuments(payable, [good, { ...bad, data: { ...bad.data, isExcluded: true } }]).duplicate, null);
const wrongDirection = reviewPayableDocuments(payable, [{ ...good, data: { ...good.data, movement: 'Entrada', type: 'Recebimento Wix / Cartao' } }]);
assert.deepEqual(wrongDirection.mismatches[0].fields, ['direction']);
assert.equal(wrongDirection.mismatches[0].requiresIdentityReview, true);
assert.ok(reviewPayableDocuments(payable, [{ ...bad, data: { ...bad.data, identificacaoUnica: 'OTHER' } }]).mismatches[0].identityReviewReasons.includes('UNIQUE_IDENTITY_CONFLICT'));
assert.equal(reviewPayableDocuments(payable, [{ ...bad, data: { ...bad.data, identificacaoUnica: 'TEST-1' } }]).mismatches[0].requiresIdentityReview, false);
assert.ok(reviewPayableDocuments(payable, [{ ...good, data: { ...good.data, valuePaid: 'invalid' } }]).mismatches[0].fields.includes('amount'));
assert.equal(reviewPayableDocuments(payable, [good, { ...good, id: 'copy' }]).duplicate.firestoreIds.length, 2);
console.log('OK: all active documents checked, duplicates exposed, identity conflicts flagged, excluded records preserved.');
